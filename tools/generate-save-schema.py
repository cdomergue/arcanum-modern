#!/usr/bin/env python3
"""Generate serialization metadata, never game text, from the pinned engine."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
header = (ROOT / "source/src/game/obj.h").read_text()
source = (ROOT / "source/src/game/obj.c").read_text()
names = re.findall(r"\bOBJ_F_[A-Z0-9_]+", header.split("typedef enum ObjectField {")[1].split("}")[0])
types = dict(re.findall(r"object_fields\[(OBJ_F_\w+)\]\.type = OD_TYPE_(\w+);", source))
groups = {}
group = None
for name in names[:names.index("OBJ_F_TOTAL_NORMAL")]:
    kind = types[name]
    if kind == "BEGIN":
        group = name.removeprefix("OBJ_F_").removesuffix("_BEGIN")
        if name == "OBJ_F_BEGIN":
            group = "BASE"
        groups[group] = []
    elif kind != "END":
        groups[group].append([name.removeprefix("OBJ_F_"), kind])
stats_header = (ROOT / "source/src/game/stat.h").read_text()
stats = re.findall(r"\bSTAT_(\w+)", stats_header.split("typedef enum Stat {")[1].split("}")[0])[:-1]
def enum_values(file, enum, prefix):
    text = (ROOT / f"source/src/game/{file}.h").read_text()
    return re.findall(rf"\b{prefix}_(\w+)", text.split(f"typedef enum {enum} {{")[1].split("}")[0])[:-1]

payload = {"groups": groups, "stats": stats,
           "skills": enum_values("skill", "Skill", "SKILL"),
           "training": enum_values("skill", "Training", "TRAINING"),
           "colleges": enum_values("spell", "College", "COLLEGE"),
           "spells": enum_values("spell", "Spell", "SPELL")}
destination = ROOT / "tools/save-editor/schema.js"
destination.parent.mkdir(parents=True, exist_ok=True)
destination.write_text("// Generated by tools/generate-save-schema.py; binary format metadata only.\n"
                       "globalThis.ArcanumSchema = " + json.dumps(payload, indent=2) + ";\n")
