#!/usr/bin/env python3
"""Generate field names/types only from pinned CE; no game resources or text."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2]
header = (root / 'source/src/game/obj.h').read_text()
source = (root / 'source/src/game/obj.c').read_text()
names = re.findall(r'\bOBJ_F_[A-Z0-9_]+', header.split('typedef enum ObjectField {')[1].split('}')[0])
types = dict(re.findall(r'object_fields\[(OBJ_F_\w+)\]\.type = OD_TYPE_(\w+);', source))
groups = {}
group = ''
for name in names[:names.index('OBJ_F_TOTAL_NORMAL')]:
    kind = types[name]
    if kind == 'BEGIN':
        group = 'BASE' if name == 'OBJ_F_BEGIN' else name.removeprefix('OBJ_F_').removesuffix('_BEGIN')
        groups[group] = []
    elif kind != 'END':
        groups[group].append((name.removeprefix('OBJ_F_'), kind))
lines = ['// Generated by generate_object_schema.py from pinned CE. Format metadata only.',
         'static const std::map<std::string, std::vector<FieldSpec>> field_groups = {']
for group, fields in groups.items():
    lines.append('    {"' + group + '", {')
    lines.extend('        {"' + name + '", "' + kind + '"},' for name, kind in fields)
    lines.append('    }},')
lines.append('};')
(Path(__file__).parent / 'src/object_schema.inc').write_text('\n'.join(lines) + '\n')
