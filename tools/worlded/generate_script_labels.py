#!/usr/bin/env python3
"""Generate opcode metadata from the pinned CE source, never from game text."""
import re
from pathlib import Path

root = Path(__file__).resolve().parents[2]
header = (root / "source/src/game/script.h").read_text()
source = (root / "source/src/game/script.c").read_text()


def enum(name):
    body = re.search(r"typedef enum " + name + r" \{(.*?)\}", header, re.S)[1]
    return re.findall(r"^\s*([A-Z][A-Z_0-9]+),", body, re.M)


def function(name):
    match = re.search(r"^\w+ " + name + r"\([^;]*?\)\s*\{", source, re.M)
    assert match, name
    start = match.end()
    depth = 1
    for i in range(start, len(source)):
        depth += (source[i] == "{") - (source[i] == "}")
        if not depth:
            return source[start:i]
    raise ValueError(name)


def operands(body, parameter):
    mask = 0
    for index in re.findall(parameter + r"->op_(?:type|value)\[([0-7])\]", body):
        mask |= 1 << int(index)
    # Some action cases delegate their operands to a helper.
    for helper in set(re.findall(r"\b(\w+)\(" + parameter + r",", body)):
        mask |= operands(function(helper), parameter)
    return mask


def object_operands(body, parameter):
    mask = 0
    for index in re.findall(r"script_(?:resolve_focus_obj|get_obj|set_obj)\(\s*" + parameter + r"->op_type\[([0-7])\]", body):
        mask |= 1 << int(index)
    for helper in set(re.findall(r"\b(\w+)\(" + parameter + r",", body)):
        mask |= object_operands(function(helper), parameter)
    return mask


output = ["// Generated by generate_script_labels.py from pinned CE; no game text."]
for name, type_name in [("attachment", "ScriptAttachmentPoint"),
                        ("condition", "ScriptConditionType"),
                        ("action", "ScriptActionType")]:
    names = enum(type_name)
    output.append(f"inline const char* {name}Names[]={{" + ",".join(f'"{n}"' for n in names) + "};")
    if name == "attachment":
        continue
    body = function("script_execute_" + name)
    prefix = "SCT_" if name == "condition" else "SAT_"
    cases = list(re.finditer(r"case (" + prefix + r"\w+):", body))
    masks = {}
    object_masks = {}
    for i, case in enumerate(cases):
        # Adjacent case labels share a handler (CALL_SCRIPT_IN/AT).
        j = i
        while True:
            end = cases[j + 1].start() if j + 1 < len(cases) else len(body)
            segment = body[cases[j].end():end]
            if segment.strip() or j + 1 == len(cases):
                break
            j += 1
        masks[case[1]] = operands(segment, name)
        object_masks[case[1]] = object_operands(segment, name)
    if name == "action":
        masks["SAT_DO_NOTHING"] = 0  # Handled by the switch default.
    assert set(masks) == set(names), (set(names) - set(masks))
    output.append(f"inline const unsigned {name}Operands[]={{")
    output.extend(f"    {masks[n]}, // {n}" for n in names)
    output.append("};")
    output.append(f"inline const unsigned {name}ObjectOperands[]={{" + ",".join(str(object_masks.get(n, 0)) for n in names) + "};")

(root / "tools/worlded/src/script_labels.inc").write_text("\n".join(output) + "\n", encoding="utf-8")
