#!/usr/bin/env python3
"""Compile the reviewed AID translations into the native interface (offline)."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'resources/aid/descriptions.json'
OUTPUT = ROOT / 'source/src/ui/modern_aid_data.inc'
TOKEN = re.compile(r'@([sktpid])(\d+)@')
LIMITS = {'s': 28, 'k': 16, 't': 8, 'p': 80, 'i': 76, 'd': 50000}


def generate():
    data = json.loads(DATA.read_text())
    entries = data['entries']
    ids = [e['id'] for e in entries]
    if ids != sorted(set(ids)):
        raise ValueError('Descriptions must have unique, sorted IDs')
    lines = ['/* Generated by tools/generate-aid.py; do not edit.',
             ' * AID by SCARaw (MIT), revision ' + data['revision'] + '.',
             ' * See resources/aid/LICENSE.txt. UTF-8; MES references stay dynamic. */',
             'static const ModernAidEntry modern_aid_entries[] = {']
    for e in entries:
        for lang in ('en', 'fr'):
            value = e[lang]
            if not value or len(value.encode('utf-8')) > 1800:
                raise ValueError(f'Invalid {lang} description: {e["id"]}')
            if '@' in TOKEN.sub('', value):
                raise ValueError(f'Malformed token: {e["id"]}')
            for kind, number in TOKEN.findall(value):
                if int(number) >= LIMITS[kind]:
                    raise ValueError(f'Invalid token: {kind}{number}')
        lines.append('    {%d, %s, %s},' % (e['id'],
                     json.dumps(e['fr'], ensure_ascii=False), json.dumps(e['en'], ensure_ascii=False)))
    lines += ['};', 'static const ModernAidVariant modern_aid_variants[] = {']
    guids = [v['guid'] for v in data['variants']]
    if guids != sorted(set(guids)):
        raise ValueError('Variants must have unique, sorted GUIDs')
    for v in data['variants']:
        if v['effect'] not in ids or not re.fullmatch(r'G_[0-9A-F_]{36}', v['guid']):
            raise ValueError(f'Invalid variant: {v}')
        lines.append('    {"%s", %d, %d},' % (v['guid'], v['description'], v['effect']))
    return '\n'.join(lines + ['};', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_text() != generated:
            raise SystemExit('AID table is stale: run python3 tools/generate-aid.py')
    else:
        OUTPUT.write_text(generated)
