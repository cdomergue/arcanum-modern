#!/usr/bin/env python3
"""Build reference-only localization and compatibility metadata for hotfix 1.1.0.
Inputs are private installed game data and the author's pinned release archives.
No original game text is copied into the resulting metadata.
"""
import argparse,gzip,hashlib,importlib.util,json,re,subprocess,sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from map_archive import Archive
spec=importlib.util.spec_from_file_location('base_plan',Path(__file__).with_name('make-plan.py'))
m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)

def digest(raw,path):
    layout={'proto/008219 - armor.pro':(534,[98,204,274,365]),
            'proto/010114 - food.pro':(464,[98,151,204,274])}.get(path)
    if layout and len(raw)==layout[0] and raw[:6]==bytes.fromhex('77000000ffff') and raw[28:30]==b'\x01\x00':
        raw=bytearray(raw)
        for a,b in [(6,28),(30,36),(40,52)]+[(i,i+4) for i in layout[1]]:raw[a:b]=bytes(b-a)
        raw=bytes(raw)
    if path.endswith(('.dlg','.mes')):raw=raw.replace(b'\r\n',b'\n')
    return hashlib.sha256(raw).hexdigest()

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--game',type=Path,required=True)
    p.add_argument('--release',type=Path,required=True)
    p.add_argument('--upstream',type=Path,required=True)
    p.add_argument('--generated-protos',type=Path,required=True,help='Pristine prototypes generated by the pinned engine')
    args=p.parse_args();data=Path(__file__).with_name('data')
    originals=m.archives(args.game)
    active=args.game/'modern-ui/uap-fr/active'
    uap=[Archive(active/n) for n in ['global/arcanum5.dat','global/arcanumxraces.dat','modules/arcanum.patch1','modules/arcanum.patch9']]
    translated=uap+[Archive(active/n) for n in ['french-global.dat','french-module.dat']]
    old=json.loads(gzip.decompress((data/'plan.json.gz').read_bytes()))
    old={f['path']:f for f in old['files']}
    plans=[];inputs={};assets={}
    for name in ['Arcanum8.dat','Arcanum.PATCH8']:
        path=args.release/name;assets[name]={'size':path.stat().st_size,'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}
        a=Archive(path)
        for resource,entry in sorted(a.entries.items()):
            raw=a.read(resource);allowed=set()
            for repos in [originals+uap,originals+translated]:
                before=m.read(repos,resource)
                allowed.add(digest(before,resource) if before else '')
            if resource=='dlg/02635sarahtoone.dlg':
                paths=subprocess.check_output(['git','-C',str(args.upstream),'ls-tree','-r','--name-only','66aa286'],text=True).splitlines()
                rel=next(n for n in paths if n.lower().endswith('/02635sarahtoone.dlg'))
                before=subprocess.check_output(['git','-C',str(args.upstream),'show','66aa286:'+rel])
                allowed.add(digest(before,resource))
            if resource.startswith('proto/'):
                generated=next(x for x in args.generated_protos.iterdir() if x.name.lower()==Path(resource).name)
                allowed.add(digest(generated.read_bytes(),resource))
            inputs[resource]=sorted(allowed)
            if not resource.endswith(('.dlg','.mes')):continue
            cols=7 if resource.endswith('.dlg') else 2
            rows=m.records(raw,cols);actions=[];previous=old.get(resource)
            if previous:
                actions=[dict(x) for x in previous['actions']]
                if resource=='dlg/01046magnus_shale_fist.dlg':
                    clone=dict(next(x for x in actions if x['id']==447 and x['column']==1));clone['id']=445;actions.append(clone)
                    actions += [dict(id=448,column=1,text='Que peux-tu me dire sur le Clan de la Roue, Magnus ?'),
                                dict(id=449,column=1,text='Sais-tu comment se rendre à Qintarra ?')]
            else:
                fr=m.records(m.read(originals,resource),cols)
                for i,row in rows.items():
                    for col in ([1,2] if cols==7 and row[3].strip() in ('','0') else [1]):
                        if not row[col].strip() or (cols==7 and m.TECHNICAL.match(row[col])):continue
                        assert i in fr,(resource,i)
                        fc=col if fr[i][col].strip() else 1
                        assert fr[i][fc].strip(),(resource,i,col)
                        actions.append(dict(id=i,column=col,source=resource,source_id=i,source_column=fc))
            assert len({(x['id'],x['column']) for x in actions})==len(actions)
            plans.append(dict(scope='module',path=resource,sha256=hashlib.sha256(raw).hexdigest(),columns=cols,actions=actions))
    (data/'hotfix-plan.json.gz').write_bytes(gzip.compress(json.dumps(dict(version=1,files=plans),ensure_ascii=True,separators=(',',':')).encode(),mtime=0))
    (data/'hotfix-catalog.json').write_text(json.dumps(dict(version='1.1.0',assets=assets,inputs=inputs),indent=2)+'\n')
    print(f'{len(inputs)} resources, {len(plans)} localized files; two new French lines')
if __name__=='__main__':main()
